import { test, expect } from "@playwright/test";
import { randomUUID } from "node:crypto";
import { mkdir } from "node:fs/promises";
import { localTestDb, cleanAccounts } from "../helpers";

test("owner can manage stock, thresholds, search, deletion, and mobile logout", async ({ page }) => {
  const db = localTestDb();
  const email = `browser-${randomUUID()}@stockflow.test`;
  const password = "Browser-stockflow-test-password";
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  try {
    await page.goto("/signup");
    await page.getByLabel("Organization name").fill("The Everyday Store");
    await page.getByLabel("Email address").fill(email);
    await page.getByLabel("Password", { exact: true }).fill(password);
    await page.getByLabel("Confirm password").fill(password);
    await page.getByRole("button", { name: "Create workspace" }).click();
    await expect(page).toHaveURL(/\/dashboard$/);
    await expect(page.getByRole("heading", { name: "Inventory overview." })).toBeVisible();
    await page.getByRole("link", { name: "Add product", exact: true }).click();
    await page.getByLabel(/Product name/).fill("Everyday canvas tote");
    await page.getByLabel(/^SKU/).fill("TOTE-001");
    await page.getByLabel(/Description/).fill("A durable everyday carry.");
    await page.getByLabel(/Quantity on hand/).fill("5");
    await page.getByLabel(/Cost price/).fill("10.25");
    await page.getByLabel(/Selling price/).fill("24.50");
    await page.getByRole("button", { name: "Create product" }).click();
    await expect(page).toHaveURL(/\/products$/);
    await expect(page.getByRole("link", { name: "Everyday canvas tote", exact: true })).toBeVisible();
    await expect(page.getByText("Low stock", { exact: true })).toBeVisible();
    await page.getByRole("link", { name: "Overview", exact: true }).click();
    await expect(page.getByRole("link", { name: "Everyday canvas tote", exact: true })).toBeVisible();
    await mkdir(".local/screenshots", { recursive: true });
    await page.screenshot({ path: ".local/screenshots/dashboard.png", fullPage: true });
    await page.getByRole("link", { name: "Edit Everyday canvas tote" }).click();
    await expect(page.getByLabel(/Selling price/)).toHaveValue("24.50");
    await page.getByLabel(/Quantity on hand/).fill("12");
    await page.getByRole("button", { name: "Save changes" }).click();
    await expect(page).toHaveURL(/\/products$/);
    await expect(page.getByText("In stock", { exact: true })).toBeVisible();
    await page.getByRole("link", { name: "Settings", exact: true }).click();
    await page.getByLabel(/Default low-stock threshold/).fill("12");
    await page.getByRole("button", { name: "Save settings" }).click();
    await expect(page.getByRole("status")).toHaveText("Your workspace settings have been saved.");
    await page.getByRole("link", { name: "Products", exact: true }).click();
    await expect(page.getByText("Low stock", { exact: true })).toBeVisible();
    await page.getByLabel("Search by name or SKU").fill("not-a-product");
    await page.getByRole("button", { name: "Search", exact: true }).click();
    await expect(page.getByRole("heading", { name: "No products found." })).toBeVisible();
    await page.getByRole("link", { name: "View all products" }).click();
    await page.getByRole("button", { name: "Delete Everyday canvas tote" }).click();
    await expect(page.getByRole("dialog")).toBeVisible();
    await page.getByRole("button", { name: "Keep product" }).click();
    await expect(page.getByRole("dialog")).not.toBeVisible();
    await page.getByRole("button", { name: "Delete Everyday canvas tote" }).click();
    await page.getByRole("button", { name: "Delete product", exact: true }).click();
    await expect(page.getByRole("heading", { name: "Let’s make room for your first product." })).toBeVisible();
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole("link", { name: "Overview", exact: true }).click();
    await expect(page.getByRole("heading", { name: "Inventory overview." })).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await page.screenshot({ path: ".local/screenshots/mobile.png", fullPage: true });
    await page.getByRole("button", { name: "Log out", exact: true }).filter({ visible: true }).click();
    await expect(page).toHaveURL(/\/login$/);
    await page.getByLabel("Email address").fill(email);
    await page.getByLabel("Password", { exact: true }).fill(password);
    await page.getByRole("button", { name: "Log in", exact: true }).click();
    await expect(page).toHaveURL(/\/dashboard$/);
    await page.reload();
    await expect(page.getByRole("heading", { name: "Inventory overview." })).toBeVisible();
    expect(errors).toEqual([]);
  } finally { await cleanAccounts(db, [email]); }
});
